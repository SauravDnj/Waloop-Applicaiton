export const flagEmoji = (code: string) => code.toUpperCase().replace(/./g, (c) => String.fromCodePoint(0x1f1e6 + c.charCodeAt(0) - 65));

const dialOf = (code: CountryCode): string => {
  try {
    return getCountryCallingCode(code);
  } catch {
    return '';
  }
};

export const COUNTRIES: Country[] = NAMES.map(([code, name]) => ({
  code,
  name,
  dial: dialOf(code),
  flag: flagEmoji(code),
})).filter((c) => c.dial);

export const countryByCode = (code?: string | null): Country | undefined => COUNTRIES.find((c) => c.code === (code ?? '').toUpperCase());

