/** Device region (SIM / OS locale) first, then the timezone, then India. */
export const detectCountry = (): Country => {
  try {
    for (const loc of getLocales()) {
      const hit = countryByCode(loc.regionCode);
      if (hit) return hit;
    }
  } catch {
    // no locale info
  }
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    const hit = countryByCode(TZ_COUNTRY[tz]);
    if (hit) return hit;
  } catch {
    // no Intl
  }
  return countryByCode('IN')!;
};

export const defaultCurrencyFor = (code: CountryCode, available: string[]): string => {
  const wanted = COUNTRY_CURRENCY[code];
  if (wanted && (!available.length || available.includes(wanted))) return wanted;
  if (available.includes('USD')) return 'USD';
  return available[0] ?? 'USD';
};

export const searchCountries = (q: string): Country[] => {
  const s = q.trim().toLowerCase().replace(/^\+/, '');
  if (!s) return COUNTRIES;
  return COUNTRIES.filter((c) => c.name.toLowerCase().includes(s) || c.code.toLowerCase() === s || c.dial.startsWith(s));
};
